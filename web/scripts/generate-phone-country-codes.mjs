/**
 * Generates src/shared/constants/phoneCountryCodes.generated.ts
 * Run: node scripts/generate-phone-country-codes.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { getCountries, getCountryCallingCode } from "libphonenumber-js";
import {
  EXPECTED_PHONE_COUNTRY_DROPDOWN_COUNT,
  PHONE_COUNTRY_SOVEREIGN_ISO_CODES,
} from "./phoneCountrySovereignIsoCodes.mjs";

const displayNames = new Intl.DisplayNames(["en"], { type: "region" });
const libIsoSet = new Set(getCountries());

const missingInLib = PHONE_COUNTRY_SOVEREIGN_ISO_CODES.filter((iso) => !libIsoSet.has(iso));
if (missingInLib.length > 0) {
  throw new Error(
    `Sovereign ISO codes missing from libphonenumber-js: ${missingInLib.join(", ")}`,
  );
}

/** @type {{ country: string; code: string; name: string }[]} */
const entries = [];

for (const iso of PHONE_COUNTRY_SOVEREIGN_ISO_CODES) {
  let name = iso;
  try {
    name = displayNames.of(iso) ?? iso;
  } catch {
    name = iso;
  }

  entries.push({
    country: iso,
    code: `+${getCountryCallingCode(iso)}`,
    name,
  });
}

if (entries.length !== EXPECTED_PHONE_COUNTRY_DROPDOWN_COUNT) {
  throw new Error(
    `Expected ${EXPECTED_PHONE_COUNTRY_DROPDOWN_COUNT} phone countries, got ${entries.length}`,
  );
}

entries.sort((a, b) => {
  if (a.country === "IN") return -1;
  if (b.country === "IN") return 1;
  return a.name.localeCompare(b.name, "en");
});

const outPath = fileURLToPath(
  new URL("../src/shared/constants/phoneCountryCodes.generated.ts", import.meta.url),
);

const body = `/* eslint-disable */
/** Auto-generated by scripts/generate-phone-country-codes.mjs — do not edit by hand. */
/** ${EXPECTED_PHONE_COUNTRY_DROPDOWN_COUNT} sovereign countries (UN members + VA + PS); E.164 via libphonenumber-js. */

export type PhoneCountryEntry = {
  /** E.164 dial prefix including "+". */
  code: string;
  /** ISO 3166-1 alpha-2. */
  country: string;
  name: string;
};

export const PHONE_COUNTRY_ENTRIES: readonly PhoneCountryEntry[] = ${JSON.stringify(entries, null, 2)} as const;

export const DEFAULT_COUNTRY_CODE = "+91" as const;
`;

writeFileSync(outPath, body, "utf8");
console.log(`Wrote ${entries.length} countries to ${outPath}`);
